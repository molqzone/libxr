#pragma once

#include <cstdint>

namespace LibXR::EtherCAT
{

/** EtherCAT application-layer state. */
enum class AlState : uint8_t
{
  INIT = 0x01,
  PRE_OPERATIONAL = 0x02,
  BOOTSTRAP = 0x03,
  SAFE_OPERATIONAL = 0x04,
  OPERATIONAL = 0x08
};

/** EtherCAT application-layer status codes used by the native device core. */
enum class AlError : uint16_t
{
  NONE = 0x0000,
  UNSPECIFIED = 0x0001,
  INVALID_STATE_CHANGE = 0x0011,
  UNKNOWN_STATE = 0x0012,
  BOOT_NOT_SUPPORTED = 0x0013,
  INVALID_MAILBOX_CONFIGURATION = 0x0016,
  INVALID_SYNC_MANAGER_CONFIGURATION = 0x0017,
  NO_VALID_INPUTS = 0x0018,
  NO_VALID_OUTPUTS = 0x0019,
  WATCHDOG = 0x001B,
  INVALID_OUTPUT_SYNC_MANAGER = 0x001D,
  INVALID_INPUT_SYNC_MANAGER = 0x001E,
  INVALID_INPUT_MAPPING = 0x0024,
  INVALID_OUTPUT_MAPPING = 0x0025,
  INVALID_INPUT_FMMU_CONFIGURATION = 0x002E,
  MAILBOX_COE = 0x0043
};

constexpr uint16_t AL_STATUS_ERROR = 0x0010U;
constexpr uint16_t AL_CONTROL_ERROR_ACKNOWLEDGE = 0x0010U;

}  // namespace LibXR::EtherCAT
